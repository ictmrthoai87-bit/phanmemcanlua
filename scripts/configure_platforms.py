"""Idempotent patches after running flutter create --platforms=android,ios ."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]


def replace_if_exists(rel, editor):
    path = root / rel
    if path.exists():
        before = path.read_text(encoding='utf-8')
        after = editor(before)
        if after != before:
            path.write_text(after, encoding='utf-8')
            print('Updated:', rel)
        else:
            print('Already configured:', rel)
    else:
        print('Not found (platform not generated yet):', rel)


def ios_plist(s):
    # V0.4 is manual-only: remove legacy camera/photo privacy prompts.
    for key in ('NSCameraUsageDescription', 'NSPhotoLibraryUsageDescription'):
        s = re.sub(
            r'^[ \t]*<key>' + key + r'</key>\s*<string>[^<]*</string>[ \t]*\n?',
            '', s, flags=re.M)
    if '<key>CFBundleDisplayName</key>' in s:
        s = re.sub(r'(<key>CFBundleDisplayName</key>\s*<string>)[^<]*(</string>)',
                   r'\g<1>Cân Lúa Pro\g<2>', s, count=1)
    else:
        s = s.replace('</dict>', '    <key>CFBundleDisplayName</key>\n    <string>Cân Lúa Pro</string>\n</dict>', 1)
    return s


def ios_podfile(s):
    if re.search(r'^\s*platform\s*:ios\s*,', s, re.M):
        s = re.sub(r"^\s*platform\s*:ios\s*,\s*['\"][^'\"]+['\"]", "platform :ios, '15.5'", s, count=1, flags=re.M)
    else:
        s = "platform :ios, '15.5'\n" + s
    marker = "flutter_additional_ios_build_settings(target)"
    addition = '''flutter_additional_ios_build_settings(target)
    target.build_configurations.each do |config|
      config.build_settings['IPHONEOS_DEPLOYMENT_TARGET'] = '15.5'
      config.build_settings['EXCLUDED_ARCHS[sdk=*]'] = 'armv7'
    end'''
    if marker in s and "config.build_settings['EXCLUDED_ARCHS[sdk=*]']" not in s:
        s = s.replace(marker, addition)
    return s


def android_manifest(s):
    # Remove permission from Android manifests generated by old versions too.
    s = re.sub(r"^[ \t]*<uses-permission\b[^>]*\bandroid:name=['\"]android\.permission\.CAMERA['\"][^>]*/>[ \t]*\n?",
               '', s, flags=re.M)
    return re.sub(r'android:label="[^"]*"', 'android:label="Cân Lúa Pro"', s, count=1)


replace_if_exists('ios/Runner/Info.plist', ios_plist)
replace_if_exists('ios/Podfile', ios_podfile)
replace_if_exists('ios/Runner.xcodeproj/project.pbxproj', lambda s: re.sub(
    r'IPHONEOS_DEPLOYMENT_TARGET = [0-9.]+;', 'IPHONEOS_DEPLOYMENT_TARGET = 15.5;', s))
replace_if_exists('android/app/src/main/AndroidManifest.xml', android_manifest)
